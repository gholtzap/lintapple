import { writeFile } from 'node:fs/promises';
import { createHighlighter } from 'shiki';
import { rules } from '../demo/rules.js';

const highlighter = await createHighlighter({ themes: ['github-light', 'github-dark'], langs: ['css', 'bash'] });
const snippets = [['npm install -D lintapple && npx lintapple init', 'bash'], ...rules.map(rule => [rule.fix, 'css'])];
const highlightedCode = Object.fromEntries(snippets.map(([code, lang]) => [code, highlighter.codeToHtml(code, {
  lang,
  themes: { light: 'github-light', dark: 'github-dark' },
  defaultColor: false,
  // Darken the orange token to meet the text contrast rule on white.
  colorReplacements: { 'github-light': { '#e36209': '#953800' } },
  transformers: [{ pre(node) { node.properties.class = 'fix-code shiki'; delete node.properties.style; delete node.properties.tabindex; } }],
})]));
highlighter.dispose();
await writeFile(new URL('../demo/highlighted-code.js', import.meta.url), `// Generated by scripts/highlight-demo.ts.\nexport const highlightedCode = ${JSON.stringify(highlightedCode, null, 2)};\n`);
await writeFile(new URL('../../demo/highlighted-code.ts', import.meta.url), `// Generated by scripts/highlight-demo.ts.\nexport const highlightedCode: Record<string, string> = ${JSON.stringify(highlightedCode, null, 2)};\n`);
